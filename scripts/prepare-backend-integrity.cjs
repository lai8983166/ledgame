const fs = require('node:fs')
const fsp = require('node:fs/promises')
const path = require('node:path')
const { createHash } = require('node:crypto')

async function writeBackendIntegrity(appDir) {
  const manifestPath = path.join(appDir, 'electron', 'backend-integrity.generated.cjs')
  const temporaryPath = `${manifestPath}.${process.pid}.tmp`
  const jarPath = path.join(appDir, 'build-resources', 'backend', 'ledGame-backend.jar')

  // A failed preparation must never leave a previous build's trust value behind.
  await fsp.rm(manifestPath, { force: true })
  try {
    const stat = await fsp.stat(jarPath)
    if (!stat.isFile() || stat.size === 0) {
      throw new Error(`Packaged backend jar is not a nonempty file: ${jarPath}`)
    }
    const hash = createHash('sha256')
    for await (const chunk of fs.createReadStream(jarPath)) hash.update(chunk)
    const manifest = { jarSha256: hash.digest('hex') }
    await fsp.mkdir(path.dirname(manifestPath), { recursive: true })
    await fsp.writeFile(temporaryPath,
      `// Generated by the beforePack hook from the backend shipped in this build.\nmodule.exports = ${JSON.stringify(manifest)}\n`,
      { encoding: 'utf8', flag: 'wx' })
    await fsp.rename(temporaryPath, manifestPath)
    return manifest
  } catch (error) {
    await fsp.rm(temporaryPath, { force: true })
    throw new Error(`Cannot prepare packaged backend integrity: ${error.message}`, { cause: error })
  }
}

async function beforePack(context) {
  const appDir = context?.packager?.info?.appDir
  if (!appDir) throw new Error('Cannot prepare backend integrity without the packaging app directory')
  await writeBackendIntegrity(appDir)
}

module.exports = beforePack
module.exports.writeBackendIntegrity = writeBackendIntegrity
